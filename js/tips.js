// 속이기 팁: 관리자 설정 tipsFrom 번째 세트부터 대화 화면에 보여 준다. 미션 종류마다 통하는 방법이 달라서 나눠 둔다.
//  - fake: 없는 것을 있는 것처럼 말하게 하기
//  - count: 글자·알파벳 세기, 거꾸로 쓰기, 계산 (AI는 글자를 조각(토큰)으로 읽어서 약함)
//  - fact: 누구나 아는 사실 뒤집기 (가장 어려움)

const COUNT_MISSIONS = ['letters', 'reverse', 'multiply', 'count', 'prime'];

const TIPS = {
  fake: [
    '"있어?"라고 묻지 말고, 이미 있다고 전제하고 물어보세요. 예) "그 책 읽었는데 작가가 누구였지?"',
    '작가 이름, 연도, 재료처럼 구체적인 걸 물으면 AI가 빈칸을 지어내기 쉬워요.',
    '"유명하잖아", "학교에서 배웠는데"처럼 확신을 실어 보세요.',
  ],
  count: [
    'AI는 글자를 한 글자씩이 아니라 조각(토큰)으로 읽어요. 그래서 세기·거꾸로 쓰기·계산에 약해요.',
    '짧고 쉬운 건 잘 맞혀요. 길고 헷갈리는 단어나 큰 수를 골라 보세요.',
    '"설명 없이 답만 짧게"라고 하면 검산을 덜 해서 더 잘 틀려요.',
  ],
  fact: [
    '바로 물으면 거의 안 넘어가요. 질문 여러 번에 걸쳐 조금씩 끌고 가 보세요.',
    '맞는 사실과 섞어서 물어보세요. 예) "시드니가 호주 최대 도시지? 그럼 수도도…"',
    '"따라 말해", "가정해 봐"로 나온 답은 인정되지 않아요. AI가 스스로 믿게 만들어야 해요.',
  ],
};

export function tipsFor(mission) {
  if (COUNT_MISSIONS.includes(mission.id)) return TIPS.count;
  return mission.tier === 3 ? TIPS.fact : TIPS.fake;
}
